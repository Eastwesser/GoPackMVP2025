package main

import (
	"container/list"
	"fmt"
)

/*
4. Очередь FIFO
Пример: Очередь задач для бота (например, "бежать", "стрелять", "прятаться").

Объяснение: Очередь позволяет обрабатывать задачи в порядке их поступления.
Очередь — это структура данных, где элементы добавляются в конец и удаляются из начала.
Это классический пример FIFO.
*/

func main() {
	tasks := list.New() // Создаем очередь задач

	/*
		Мы используем PushBack для добавления задач в конец очереди.
		Front() возвращает первый элемент (голову очереди).
		Remove() удаляет элемент из очереди после обработки.
		Очередь обрабатывает задачи строго в порядке их добавления.
	*/

	// Добавляем задачи в очередь
	tasks.PushBack("Run")   // Бежать
	tasks.PushBack("Shoot") // Стрелять
	tasks.PushBack("Hide")  // Прятаться

	// Обрабатываем задачи в порядке их поступления
	for tasks.Len() > 0 {
		// Получаем задачу из начала очереди
		task := tasks.Front()
		fmt.Println("Processing Task:", task.Value)

		// Удаляем задачу из очереди после обработки
		tasks.Remove(task)
	}

	fmt.Println("All tasks processed.")
}
