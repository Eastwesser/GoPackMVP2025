package main

import (
	"container/list"
	"fmt"
)

/*
5. Дек (это та же очередь, но мы можем вставлять значения и в начало, и в конец)
Пример: Очередь задач для бота (например, "бежать", "стрелять", "прятаться").

Объяснение: Очередь позволяет обрабатывать задачи в порядке их поступления.
Дек — это двусторонняя очередь, где элементы можно добавлять и удалять как с начала, так и с конца.
Это делает её более гибкой, чем обычная очередь.
*/

func main() {
	tasks := list.New() // Создаем дек задач

	/*
		Мы используем PushBack для добавления задач в конец дека и PushFront для добавления задач в начало.
		Front() возвращает первый элемент, а Back() — последний.
		Дек позволяет обрабатывать задачи как с начала (срочные), так и с конца (обычные).
		Это полезно, когда нужно управлять приоритетами задач.
	*/

	// Добавляем задачи в дек
	tasks.PushBack("Shoot") // Обычная задача (в конец)
	tasks.PushFront("Hide") // Срочная задача (в начало)
	tasks.PushBack("Run")   // Обычная задача (в конец)
	tasks.PushFront("Heal") // Срочная задача (в начало)

	// Обрабатываем задачи
	for tasks.Len() > 0 {
		// Обрабатываем срочные задачи из начала дека
		frontTask := tasks.Front()
		fmt.Println("Processing Front Task:", frontTask.Value)
		tasks.Remove(frontTask)

		// Если есть задачи в конце, обрабатываем их
		if tasks.Len() > 0 {
			backTask := tasks.Back()
			fmt.Println("Processing Back Task:", backTask.Value)
			tasks.Remove(backTask)
		}
	}

	fmt.Println("All tasks processed.")
}
